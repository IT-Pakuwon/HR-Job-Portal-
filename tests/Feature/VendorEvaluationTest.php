    }

    public function test_missing_extra_or_invalid_scores_do_not_write_partial_evaluations(): void
    {
        $payload = $this->payload();
        unset($payload['template_vpe_id']);
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable()->assertJsonValidationErrors('template_vpe_id');
        $payload = $this->payload();
        $payload['ratings'] = [];
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable()->assertJsonValidationErrors('ratings');
        $payload = $this->payload();
        $firstRating = array_key_first($payload['ratings']);
        $payload['ratings'][$firstRating] = '';
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable()->assertJsonValidationErrors('ratings.'.$firstRating);
        $payload = $this->payload();
        array_pop($payload['ratings']);
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable();
        $payload = $this->payload();
        $payload['ratings']['unknown'] = 4;
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable();
        $payload = $this->payload();
        $payload['ratings'][array_key_first($payload['ratings'])] = 6;
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable();
        $this->assertSame(0, $this->db->table('tr_vendor_perfomance')->count());
        $this->assertSame(0, $this->db->table('tr_vendor_perfomance_detail')->count());
    }

    public function test_revision_resubmission_completion_and_locked_records(): void
    {
        $payload = $this->payload();
        $this->post('/evaluasivendor', $payload)->assertRedirect();
        $id = $this->db->table('tr_vendor_perfomance')->value('id');
        $this->postJson('/evaluasivendor/'.$id.'/status', ['status' => 'D'])->assertUnprocessable();
        $this->post('/evaluasivendor/'.$id.'/status', ['status' => 'D', 'comment' => 'Periksa kembali'])->assertRedirect();
        $this->getJson('/evaluasivendor/json?scope=revised')->assertOk()->assertJsonPath('recordsTotal', 1);
        $payload['ratings'] = array_map(fn () => 3, $payload['ratings']);
        $this->put('/evaluasivendor/'.$id, $payload)->assertRedirect();
        $this->assertEquals(80, $this->db->table('tr_vendor_perfomance')->value('template_vpe_aspect_grandtotal_score'));
        $this->assertSame('P', $this->db->table('tr_vendor_perfomance')->value('status'));
        $this->post('/evaluasivendor/'.$id.'/status', ['status' => 'C'])->assertRedirect();
        $this->assertSame(['C'], $this->db->table('tr_vendor_perfomance_detail')->distinct()->pluck('status')->all());
        $this->putJson('/evaluasivendor/'.$id, $payload)->assertStatus(409);
        $this->postJson('/evaluasivendor/'.$id.'/status', ['status' => 'R', 'comment' => 'Late'])->assertStatus(409);
    }

    public function test_rejected_evaluation_is_locked_and_source_becomes_available_again(): void
    {
