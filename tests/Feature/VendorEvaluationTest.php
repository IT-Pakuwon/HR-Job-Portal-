    public function test_revised_document_opens_edit_and_can_resubmit_with_another_template(): void
    {
        $this->app['events']->forget('composing: *');
        $this->withoutVite();
        $this->post('/evaluasivendor', $this->payload())->assertRedirect();
        $row = $this->db->table('tr_vendor_perfomance')->first();
        $hash = \Vinkla\Hashids\Facades\Hashids::encode($row->id);
        $this->postJson('/evaluasivendor/'.$hash.'/approval/revise', ['comment' => 'Perbaiki jenis pekerjaan dan bukti lapangan'])->assertOk();
        $this->getJson('/evaluasivendor/json?scope=revised')->assertOk()
            ->assertJsonPath('data.0.url', route('editevaluasivendor', $hash));
        $this->get('/editevaluasivendor/'.$hash.'?embed=1')->assertOk()->assertSee('Edit Penilaian Vendor')
            ->assertSee('Submit Ulang Approval')->assertSee('Perbaiki jenis pekerjaan dan bukti lapangan')
