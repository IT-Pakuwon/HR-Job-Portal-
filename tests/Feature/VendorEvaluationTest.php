        $this->assertEquals(100, $updated->template_vpe_aspect_grandtotal_score);
        $this->assertSame(11, $this->db->table('tr_vendor_perfomance_detail')->count());
        $this->assertSame(['VPE-FIRE-ALARM'], $this->db->table('tr_vendor_perfomance_detail')->distinct()->pluck('template_vpe_id')->all());
