            ->pluck('template_vpe_subaspect_id')->mapWithKeys(fn ($id) => [$id => 4])->all();
        $payload['notes'] = ['VPE-FIRE-ALARM-A01-S01' => 'Bukti revisi baru'];
        $this->putJson('/evaluasivendor/'.$row->id, $payload)->assertOk()
            ->assertJsonPath('redirect', route('showevaluasivendor', $hash));
        $updated = $this->db->table('tr_vendor_perfomance')->first();
        $this->assertSame($row->vendor_perfomance_id, $updated->vendor_perfomance_id);
        $this->assertSame('P', $updated->status);
