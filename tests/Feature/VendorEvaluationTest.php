<?php

namespace Tests\Feature;

use App\Models\User;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

class VendorEvaluationTest extends TestCase
{
    private $db;

    protected function setUp(): void
    {
        parent::setUp();
        config(['session.driver' => 'array', 'cache.default' => 'array']);
        $this->db = DB::connection('pgsql');
        $this->db->beginTransaction();
        // Session-local tables: no application records or public sequences are changed.
        foreach (['tr_po', 'tr_kontrak', 'tr_vendor_perfomance', 'tr_vendor_perfomance_detail'] as $table) {
            $this->db->statement('CREATE TEMP TABLE '.$table.' (LIKE public.'.$table.') ON COMMIT DROP');
            $this->db->statement('ALTER TABLE pg_temp.'.$table.' ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
        }
        foreach (['ms_template_vendor_perfomance', 'ms_template_vendor_perfomance_detail', 'ms_template_vendor_perfomance_score'] as $table) {
            $this->db->statement('CREATE TEMP TABLE '.$table.' ON COMMIT DROP AS SELECT * FROM public.'.$table);
        }
        $this->actingAs(new User(['id' => 999999, 'username' => 'evaluation_test', 'user_role' => 'admin', 'status' => 'A']));
        $this->db->table('tr_po')->insert(['id' => 101, 'ponbr' => 'PO-TEST', 'cpny_id' => 'TEST', 'vendorid' => 'VTEST',
            'vendorname' => 'Vendor Test', 'department_id' => 'ENG', 'status' => 'P',
            'spkstartworkingdate' => '2026-01-01', 'spkendtworkingdate' => '2026-12-31']);
        $this->db->table('tr_kontrak')->insert(['id' => 201, 'kontrakid' => 'KT-TEST', 'cpny_id' => 'TEST',
            'vendorname' => 'Vendor Kontrak', 'status' => 'C', 'startdate' => '2026-01-01', 'enddate' => '2026-12-31']);
    }

    protected function tearDown(): void
    {
        if ($this->db) {
            $this->db->rollBack();
        }
        parent::tearDown();
    }

    private function payload(string $type = 'PO'): array
    {
        $ratings = $this->db->table('ms_template_vendor_perfomance_detail')->where('template_vpe_id', 'VPE-CHILLER')
            ->pluck('template_vpe_subaspect_id')->mapWithKeys(fn ($id) => [$id => 4])->all();
        return ['source_type' => $type, 'source_id' => $type === 'PO' ? 101 : 201,
            'template_vpe_id' => 'VPE-CHILLER', 'vendor_perfomance_date' => '2026-11-16',
            'vendor_perfomance_start_date' => '2026-01-01', 'vendor_perfomance_end_date' => '2026-12-31', 'ratings' => $ratings];
    }

    public function test_jobs_include_po_and_contract_and_exclude_unapproved_sources(): void
    {
        $this->db->table('tr_po')->insert(['ponbr' => 'PO-DRAFT', 'status' => 'H']);
        $this->getJson('/evaluasivendor/json?scope=jobs')->assertOk()->assertJsonPath('recordsTotal', 2)
            ->assertJsonFragment(['document_no' => 'PO-TEST', 'source_type' => 'PO'])
            ->assertJsonFragment(['document_no' => 'KT-TEST', 'source_type' => 'KONTRAK']);
        $this->getJson('/evaluasivendor/json?scope=jobs&source_type=KONTRAK')->assertOk()->assertJsonPath('recordsFiltered', 1);
        $this->getJson('/evaluasivendor/json?scope=jobs&end_date=2026-12-31')->assertOk()->assertJsonPath('recordsFiltered', 2);
        $this->getJson('/evaluasivendor/json?scope=jobs&start_date=2027-01-01&end_date=2026-12-31')->assertUnprocessable();
    }

    public function test_store_uses_source_identity_and_server_computed_scores_and_prevents_duplicates(): void
    {
        $payload = array_merge($this->payload(), ['vendorname' => 'Forged', 'status' => 'C', 'template_vpe_aspect_grandtotal_score' => 999]);
        $payload['notes'] = ['VPE-CHILLER-A01-S01' => 'Bukti inspeksi lapangan'];
        $this->post('/evaluasivendor', $payload)->assertRedirect();
        $row = $this->db->table('tr_vendor_perfomance')->first();
        $this->assertSame('Vendor Test', $row->vendorname);
        $this->assertSame('P', $row->status);
        $this->assertEquals(100, $row->template_vpe_aspect_grandtotal_score);
        $this->assertSame('Sangat Baik', $row->template_vpe_aspect_result);
        $this->assertSame(14, $this->db->table('tr_vendor_perfomance_detail')->count());
        $this->assertSame('Bukti inspeksi lapangan', $this->db->table('tr_vendor_perfomance_detail')->where('template_vpe_subaspect_id', 'VPE-CHILLER-A01-S01')->value('template_vpe_subaspect_note'));
        $this->getJson('/evaluasivendor/json?scope=jobs')->assertOk()->assertJsonPath('recordsTotal', 1);
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable()->assertJsonValidationErrors('source_id');
        $this->assertSame(1, $this->db->table('tr_vendor_perfomance')->count());
    }

    public function test_contract_creation_preserves_contract_reference_and_status_tabs(): void
    {
        $this->post('/evaluasivendor', $this->payload('KONTRAK'))->assertRedirect();
        $row = $this->db->table('tr_vendor_perfomance')->first();
        $this->assertSame('KT-TEST', $row->ponbr);
        $this->assertSame('KONTRAK', $row->vendor_perfomance_type);
        $this->getJson('/evaluasivendor/json?scope=onprogress')->assertOk()->assertJsonPath('recordsTotal', 1);
        $this->getJson('/evaluasivendor/json?scope=completed')->assertOk()->assertJsonPath('recordsTotal', 0);
        $this->getJson('/evaluasivendor/json?scope=all')->assertOk()->assertJsonPath('recordsTotal', 1);
    }

    public function test_missing_extra_or_invalid_scores_do_not_write_partial_evaluations(): void
    {
        $payload = $this->payload();
        array_pop($payload['ratings']);
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable();
        $payload = $this->payload();
        $payload['ratings']['unknown'] = 4;
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable();
        $payload = $this->payload();
        $payload['ratings'][array_key_first($payload['ratings'])] = 6;
        $this->postJson('/evaluasivendor', $payload)->assertUnprocessable();
        $this->assertSame(0, $this->db->table('tr_vendor_perfomance')->count());
        $this->assertSame(0, $this->db->table('tr_vendor_perfomance_detail')->count());
    }

    public function test_revision_resubmission_completion_and_locked_records(): void
    {
        $payload = $this->payload();
        $this->post('/evaluasivendor', $payload)->assertRedirect();
        $id = $this->db->table('tr_vendor_perfomance')->value('id');
        $this->postJson('/evaluasivendor/'.$id.'/status', ['status' => 'D'])->assertUnprocessable();
        $this->post('/evaluasivendor/'.$id.'/status', ['status' => 'D', 'comment' => 'Periksa kembali'])->assertRedirect();
        $this->getJson('/evaluasivendor/json?scope=revised')->assertOk()->assertJsonPath('recordsTotal', 1);
        $payload['ratings'] = array_map(fn () => 3, $payload['ratings']);
        $this->put('/evaluasivendor/'.$id, $payload)->assertRedirect();
        $this->assertEquals(80, $this->db->table('tr_vendor_perfomance')->value('template_vpe_aspect_grandtotal_score'));
        $this->assertSame('P', $this->db->table('tr_vendor_perfomance')->value('status'));
        $this->post('/evaluasivendor/'.$id.'/status', ['status' => 'C'])->assertRedirect();
        $this->assertSame(['C'], $this->db->table('tr_vendor_perfomance_detail')->distinct()->pluck('status')->all());
        $this->putJson('/evaluasivendor/'.$id, $payload)->assertStatus(409);
        $this->postJson('/evaluasivendor/'.$id.'/status', ['status' => 'R', 'comment' => 'Late'])->assertStatus(409);
    }

    public function test_rejected_evaluation_is_locked_and_source_becomes_available_again(): void
    {
        $payload = $this->payload();
        $this->post('/evaluasivendor', $payload)->assertRedirect();
        $id = $this->db->table('tr_vendor_perfomance')->value('id');
        $this->post('/evaluasivendor/'.$id.'/status', ['status' => 'R', 'comment' => 'Tidak sesuai'])->assertRedirect();
        $this->getJson('/evaluasivendor/json?scope=rejected')->assertOk()->assertJsonPath('recordsTotal', 1);
        $this->putJson('/evaluasivendor/'.$id, $payload)->assertStatus(409);
        $this->getJson('/evaluasivendor/json?scope=jobs')->assertOk()->assertJsonPath('recordsTotal', 2);
    }

    public function test_new_module_is_restricted_to_global_settings_admin(): void
    {
        $this->actingAs(new User(['username' => 'not_admin', 'user_role' => 'user', 'status' => 'A']));
        $this->getJson('/evaluasivendor/json')->assertForbidden();
        $this->postJson('/evaluasivendor', $this->payload())->assertForbidden();
    }

    public function test_list_create_edit_and_readonly_views_render(): void
    {
        // Isolate the module from shared navigation database queries.
        $this->app['events']->forget('composing: *');
        $this->withoutVite();
        $this->get('/evaluasivendor?embed=1')->assertOk()->assertSee('Penilaian Vendor')->assertSee('evaluation-table');
        $this->get('/evaluasivendor/create?source_type=PO&source_id=101&embed=1')->assertOk()->assertSee('Input Penilaian Vendor')->assertSee('Maintenance Chiller');
        $this->getJson('/evaluasivendor/templates/VPE-CHILLER')->assertOk()->assertJsonCount(14, 'details');
        $this->post('/evaluasivendor', $this->payload())->assertRedirect();
        $id = $this->db->table('tr_vendor_perfomance')->value('id');
        $this->get('/evaluasivendor/'.$id.'?embed=1')->assertOk()->assertSee('Simpan On Progress')->assertSee('Proses Penilaian');
        $this->post('/evaluasivendor/'.$id.'/status', ['status' => 'C'])->assertRedirect();
        $this->get('/evaluasivendor/'.$id.'?embed=1')->assertOk()->assertSee('Completed')->assertDontSee('id="save-evaluation"', false)->assertDontSee('Proses Penilaian');
    }
}
