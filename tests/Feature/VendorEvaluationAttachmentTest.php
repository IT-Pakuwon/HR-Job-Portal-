<?php

namespace Tests\Feature;

use App\Http\Controllers\EvaluasiVendorController;
use App\Models\TrVendorPerfomance;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;
use Tests\TestCase;

class VendorEvaluationAttachmentTest extends TestCase
{
    protected function setUp(): void
    {
        parent::setUp();
        foreach (['pgsql' => 'tr_vendor_perfomance_detail', 'pgsql2' => 'tr_attachment'] as $connection => $table) {
            $db = DB::connection($connection);
            $db->beginTransaction();
            $db->statement('CREATE TEMP TABLE '.$table.' (LIKE public.'.$table.') ON COMMIT DROP');
            $db->statement('ALTER TABLE pg_temp.'.$table.' ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
        }
    }

    protected function tearDown(): void
    {
        DB::connection('pgsql2')->rollBack();
        DB::connection('pgsql')->rollBack();
        parent::tearDown();
    }

    public function test_multiple_files_are_linked_to_the_correct_detail_and_document(): void
    {
        DB::connection('pgsql')->table('tr_vendor_perfomance_detail')->insert([
            ['id' => 21, 'vendor_perfomance_id' => 'VE26110001', 'vendor_perfomance_type' => 'SPK', 'ponbr' => 'SPK1', 'cpny_id' => 'AW', 'template_vpe_subaspect_id' => 'S1'],
            ['id' => 22, 'vendor_perfomance_id' => 'VE26110001', 'vendor_perfomance_type' => 'SPK', 'ponbr' => 'SPK1', 'cpny_id' => 'AW', 'template_vpe_subaspect_id' => 'S2'],
        ]);
        $evaluation = new TrVendorPerfomance(['vendor_perfomance_id' => 'VE26110001', 'vendor_perfomance_type' => 'SPK', 'ponbr' => 'SPK1', 'cpny_id' => 'AW', 'department_id' => 'IT']);
        $controller = new class extends EvaluasiVendorController {
            protected function gcsUpload(UploadedFile $file, string $folder): string
            {
                return $folder.'/'.$file->getClientOriginalName();
            }
        };
        $paths = [];
        $method = new \ReflectionMethod(EvaluasiVendorController::class, 'saveAttachmentsEvaluasi');
        $method->invokeArgs($controller, [$evaluation, ['S1' => [UploadedFile::fake()->create('laporan.pdf', 10), UploadedFile::fake()->create('foto.jpg', 10)], 'S2' => [UploadedFile::fake()->create('bukti.pdf', 10)]], 'tester', &$paths]);

        $rows = DB::connection('pgsql2')->table('tr_attachment')->orderBy('id')->get();
        $this->assertCount(3, $rows);
        $this->assertSame(['21', '21', '22'], $rows->pluck('reference_id')->all());
        $this->assertSame(['VE', 'VE', 'VE'], $rows->pluck('doctype')->all());
        $this->assertSame(['VE26110001', 'VE26110001', 'VE26110001'], $rows->pluck('refnbr')->all());
        $this->assertCount(3, $paths);
    }

    public function test_unknown_detail_is_rejected_before_upload(): void
    {
        $evaluation = new TrVendorPerfomance(['vendor_perfomance_id' => 'VE1', 'vendor_perfomance_type' => 'SPK', 'ponbr' => 'SPK1', 'cpny_id' => 'AW']);
        $paths = [];
        $method = new \ReflectionMethod(EvaluasiVendorController::class, 'saveAttachmentsEvaluasi');
        $this->expectException(ValidationException::class);
        $method->invokeArgs(new EvaluasiVendorController(), [$evaluation, ['UNKNOWN' => [UploadedFile::fake()->create('test.pdf')]], 'tester', &$paths]);
    }

    public function test_attachment_list_excludes_other_documents_and_inactive_files(): void
    {
        $evaluation = new TrVendorPerfomance(['vendor_perfomance_id' => 'VE1', 'cpny_id' => 'AW', 'department_id' => 'IT']);
        $evaluation->id = 1;
        DB::connection('pgsql2')->table('tr_attachment')->insert([
            ['id' => 1, 'refnbr' => 'VE1', 'doctype' => 'VE', 'cpny_id' => 'AW', 'department_id' => 'IT', 'reference_id' => '21', 'status' => 'A', 'attachment_name' => 'valid', 'extention' => 'pdf'],
            ['id' => 2, 'refnbr' => 'VE2', 'doctype' => 'VE', 'cpny_id' => 'AW', 'department_id' => 'IT', 'reference_id' => '21', 'status' => 'A', 'attachment_name' => 'other', 'extention' => 'pdf'],
            ['id' => 3, 'refnbr' => 'VE1', 'doctype' => 'VE', 'cpny_id' => 'AW', 'department_id' => 'IT', 'reference_id' => '21', 'status' => 'X', 'attachment_name' => 'deleted', 'extention' => 'pdf'],
            ['id' => 4, 'refnbr' => 'VE1', 'doctype' => 'VE', 'cpny_id' => 'AW', 'department_id' => 'IT', 'reference_id' => '22', 'status' => 'A', 'attachment_name' => 'other detail', 'extention' => 'pdf'],
        ]);
        $method = new \ReflectionMethod(EvaluasiVendorController::class, 'attachmentListEvaluasi');
        $list = $method->invoke(new EvaluasiVendorController(), $evaluation, collect([(object) ['id' => 21]]));
        $this->assertSame([1], array_column($list[21], 'id'));
        $this->assertSame('valid.pdf', $list[21][0]['name']);
    }
}
